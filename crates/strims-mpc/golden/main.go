// run runs a and b concurrently over a recording pipe and returns the bytes
// each side wrote.
func run(a func(c mpc.Conn) error, b func(c mpc.Conn) error) (aSent, bSent []byte, err error) {
	ca, cb := pipe()
	errs := make(chan error, 1)
	go func() {
		errs <- a(ca)
	}()
	if err := b(cb); err != nil {
		return nil, nil, err
	}
	if err := <-errs; err != nil {
		return nil, nil, err
	}
	return ca.sent.Bytes(), cb.sent.Bytes(), nil
}

func writeTranscripts(w io.Writer) error {
	fmt.Fprintln(w, "# generated by: go run -tags golden ./crates/strims-mpc/golden transcripts")

	// OT: the sender's base OT is the receiver's ot kind's sender, etc. The
	// sender uses AESRNG(seed_s), the receiver AESRNG(seed_r).
	otCases := []struct {
		kind string
		n    int
	}{
		{"np", 10}, {"co", 10}, {"co", 1}, {"alsz-np", 5}, {"alsz-np", 10}, {"alsz-np", 200},
		{"alsz-co", 64}, {"kos-np", 10}, {"kos-np", 13}, {"kos-co", 100}, {"kos-co", 0},
	}
	for ci, c := range otCases {
		k := otKinds[c.kind]
		inRNG := newRNG(seed(byte(40 + ci)))
		values := make([][2]mpc.Block, c.n)
		var flat [][]byte
		for i := range values {
			values[i][0] = readBlock(inRNG)
			values[i][1] = readBlock(inRNG)
			flat = append(flat, values[i][0][:], values[i][1][:])
		}
		choices := boolsFromBytes(read(inRNG, (c.n+7)/8))[:c.n]
		var bits strings.Builder
		for _, v := range choices {
			if v {
				bits.WriteByte('1')
			} else {
				bits.WriteByte('0')
			}
		}
		seedS, seedR := seed(byte(60+ci)), seed(byte(80+ci))
		var res []mpc.Block
		sSent, rSent, err := run(
			func(conn mpc.Conn) error {
				rng := newRNG(seedS)
				ot, err := k.sender(conn, rng)
				if err != nil {
					return err
				}
				return ot.Send(conn, values, rng)
			},
			func(conn mpc.Conn) error {
				rng := newRNG(seedR)
				ot, err := k.receiver(conn, rng)
				if err != nil {
					return err
				}
				res, err = ot.Receive(conn, choices, rng)
				return err
			},
		)
		if err != nil {
			return err
		}
		for i, r := range res {
			want := values[i][0]
			if choices[i] {
				want = values[i][1]
			}
			if r != want {
				return fmt.Errorf("ot %s: wrong output", c.kind)
			}
		}
		fmt.Fprintf(w, "ot kind=%s seed_s=%s seed_r=%s values=%s choices=%s s2r_len=%d s2r_sha256=%s r2s_len=%d r2s_sha256=%s\n",
			c.kind, h(seedS), h(seedR), hexList(flat), bits.String(), len(sSent), sum(sSent), len(rSent), sum(rSent))
	}

	// KKRT: the OPRF sender runs the OT extension receiver.
	kkrtCases := []struct {
		kind string
		m    int
	}{
		{"kos-np", 100}, {"kos-co", 3}, {"alsz-co", 20}, {"kos-co", 600},
	}
	for ci, c := range kkrtCases {
		k := otKinds[c.kind]
		inRNG := newRNG(seed(byte(120 + ci)))
		inputs := make([]mpc.Block, c.m)
		var flat [][]byte
		for i := range inputs {
			inputs[i] = readBlock(inRNG)
			flat = append(flat, inputs[i][:])
		}
		seedS, seedR := seed(byte(140+ci)), seed(byte(160+ci))
		var outputs []mpc.Block512
		var computed []mpc.Block512
		sSent, rSent, err := run(
			func(conn mpc.Conn) error {
				rng := newRNG(seedS)
				ot, err := k.receiver(conn, rng)
				if err != nil {
					return err
				}
				oprf, err := mpc.NewKKRTSender(conn, ot, rng)
				if err != nil {
					return err
				}
				seeds, err := oprf.Send(conn, c.m, rng)
				if err != nil {
					return err
				}
				for i, in := range inputs {
					computed = append(computed, oprf.Compute(seeds[i], in))
				}
				return nil
			},
			func(conn mpc.Conn) error {
				rng := newRNG(seedR)
				ot, err := k.sender(conn, rng)
				if err != nil {
					return err
				}
				oprf, err := mpc.NewKKRTReceiver(conn, ot, rng)
				if err != nil {
					return err
				}
				outputs, err = oprf.Receive(conn, inputs, rng)
				return err
			},
		)
		if err != nil {
			return err
		}
		var outBytes []byte
		for i := range outputs {
			if outputs[i] != computed[i] {
				return fmt.Errorf("kkrt: output mismatch")
			}
			outBytes = append(outBytes, outputs[i][:]...)
		}
		fmt.Fprintf(w, "kkrt kind=%s seed_s=%s seed_r=%s inputs=%s s2r_len=%d s2r_sha256=%s r2s_len=%d r2s_sha256=%s outputs_sha256=%s\n",
			c.kind, h(seedS), h(seedR), hexList(flat), len(sSent), sum(sSent), len(rSent), sum(rSent), sum(outBytes))
	}

	// PSZ with the broker's composition. Elements have mixed lengths so both
	// digest paths run; the first ilen receiver elements are shared, placed
	// in reverse order at the end of the sender's set.
	pszCases := [][3]int{{0, 0, 0}, {1, 0, 0}, {0, 1, 0}, {1, 1, 1}, {5, 7, 3}, {15, 15, 15}, {100, 80, 10}, {300, 260, 120}}
	for ci, c := range pszCases {
		alen, blen, ilen := c[0], c[1], c[2]
		inRNG := newRNG(seed(byte(180 + ci)))
		elem := func() []byte {
			n := 1 + int(read(inRNG, 1)[0]%40)
			return read(inRNG, n)
		}
		aset := make([][]byte, alen)
		bset := make([][]byte, blen)
		for i := range aset {
			aset[i] = elem()
		}
		for i := range bset {
			bset[i] = elem()
		}
		for i := 0; i < ilen; i++ {
			aset[alen-1-i] = bset[i]
		}
		seedS, seedR := seed(byte(200+ci)), seed(byte(220+ci))
		var results [][]byte
		sSent, rSent, err := run(
			func(conn mpc.Conn) error {
				rng := newRNG(seedS)
				ot, err := mpc.NewChaoOrlandiSender(conn, rng)
				if err != nil {
					return err
				}
				ote, err := mpc.NewKOSReceiver(conn, ot, rng)
				if err != nil {
					return err
				}
				oprf, err := mpc.NewKKRTSender(conn, ote, rng)
				if err != nil {
					return err
				}
				psi, err := mpc.NewPSZSender(oprf)
				if err != nil {
					return err
				}
				return psi.Send(conn, aset, rng)
			},
			func(conn mpc.Conn) error {
				rng := newRNG(seedR)
				ot, err := mpc.NewChaoOrlandiReceiver(conn, rng)
				if err != nil {
					return err
				}
				ote, err := mpc.NewKOSSender(conn, ot, rng)
				if err != nil {
					return err
				}
				oprf, err := mpc.NewKKRTReceiver(conn, ote, rng)
				if err != nil {
					return err
				}
				psi, err := mpc.NewPSZReceiver(oprf)
				if err != nil {
					return err
				}
				results, err = psi.Receive(conn, bset, rng)
				return err
			},
		)
		if err != nil {
			return err
		}

		// The sender's last 3*alen*maskSize bytes are shuffled with Go's
		// math/rand, which the port doesn't reproduce. Hash them sorted.
		n := alen
		if blen > n {
			n = blen
		}
		maskSize, err := computeMaskSize(n)
		if err != nil {
			return err
		}
		tail := 3 * alen * maskSize
		prefix := sSent[:len(sSent)-tail]
		var sorted []byte
		for i := 0; i < 3; i++ {
			seg := sSent[len(prefix)+i*alen*maskSize : len(prefix)+(i+1)*alen*maskSize]
			var masks [][]byte
			for j := 0; j < alen; j++ {
				masks = append(masks, seg[j*maskSize:(j+1)*maskSize])
			}
			sort.Slice(masks, func(i, j int) bool { return bytes.Compare(masks[i], masks[j]) < 0 })
			sorted = append(sorted, bytes.Join(masks, nil)...)
		}

		fmt.Fprintf(w, "psz seed_s=%s seed_r=%s sender=%s receiver=%s s2r_len=%d s2r_prefix_sha256=%s s2r_tail_sorted_sha256=%s r2s_len=%d r2s_sha256=%s result=%s\n",
			h(seedS), h(seedR), hexList(aset), hexList(bset), len(sSent), sum(prefix), sum(sorted), len(rSent), sum(rSent), hexList(results))
	}
	return nil
}

type stdioConn struct {
	*bufio.Reader
	*bufio.Writer
}

func runPSZ(role, seedHex string, args []string) error {
	var sd []byte
	if seedHex != "" {
		var err error
		if sd, err = hex.DecodeString(seedHex); err != nil {
			return err
		}
	} else {
		sd = make([]byte, 16)
		if _, err := rand.Read(sd); err != nil {
			return err
		}
	}
	rng, err := mpc.NewAESRNG(sd)
	if err != nil {
		return err
	}

	inputs := make([][]byte, len(args))
	for i, a := range args {
		if inputs[i], err = hex.DecodeString(a); err != nil {
			return err
		}
	}

	c := stdioConn{bufio.NewReader(os.Stdin), bufio.NewWriter(os.Stdout)}

	// Same composition as internal/network/broker.go.
	if role == "psz-send" {
		ot, err := mpc.NewChaoOrlandiSender(c, rng)
		if err != nil {
			return err
		}
		ote, err := mpc.NewKOSReceiver(c, ot, rng)
		if err != nil {
			return err
		}
		oprf, err := mpc.NewKKRTSender(c, ote, rng)
		if err != nil {
			return err
		}
		psi, err := mpc.NewPSZSender(oprf)
		if err != nil {
			return err
		}
		return psi.Send(c, inputs, rng)
	}

	ot, err := mpc.NewChaoOrlandiReceiver(c, rng)
	if err != nil {
		return err
	}
	ote, err := mpc.NewKOSSender(c, ot, rng)
	if err != nil {
		return err
	}
	oprf, err := mpc.NewKKRTReceiver(c, ote, rng)
	if err != nil {
		return err
	}
	psi, err := mpc.NewPSZReceiver(oprf)
	if err != nil {
		return err
	}
	results, err := psi.Receive(c, inputs, rng)
	if err != nil {
		return err
	}
	for _, r := range results {
		fmt.Fprintf(os.Stderr, "result %s\n", h(r))
	}
	fmt.Fprintln(os.Stderr, "done")
	return nil
}
