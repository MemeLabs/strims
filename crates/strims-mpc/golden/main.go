// Golden-vector generator and protocol peer for crates/strims-mpc.
//
// Run from the repo root:
//
//	go run -tags golden ./crates/strims-mpc/golden vectors > crates/strims-mpc/golden/vectors.txt
//	go run -tags golden ./crates/strims-mpc/golden transcripts > crates/strims-mpc/golden/transcripts.txt
//	go run -tags golden ./crates/strims-mpc/golden [-seed hex] psz-send <hex inputs...>
//	go run -tags golden ./crates/strims-mpc/golden [-seed hex] psz-recv <hex inputs...>
//
// The psz roles speak the broker's PSI composition (ChouOrlandi -> KOS ->
// KKRT -> PSZ, see internal/network/broker.go) over stdin/stdout. The
// receiver prints each element of the intersection to stderr as
// "result <hex>" and exits 0 on success.
//
// Output lines are "<kind> key=value ..." with hex values; lists are comma
// separated.
