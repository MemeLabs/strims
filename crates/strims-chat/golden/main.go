// ---- tables ----

type runeRange struct{ lo, hi rune }

func ranges(pred func(rune) bool) []runeRange {
	var out []runeRange
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xd800 && r <= 0xdfff {
			continue
		}
		if !pred(r) {
			continue
		}
		if n := len(out); n > 0 && out[n-1].hi == r-1 {
			out[n-1].hi = r
		} else {
			out = append(out, runeRange{r, r})
		}
	}
	return out
}

type lowerRun struct{ lo, hi, stride, delta rune }

func lowerRuns() []lowerRun {
	var runs []lowerRun
	for r := rune(0); r <= unicode.MaxRune; r++ {
		l := unicode.ToLower(r)
		if l == r {
			continue
		}
		d := l - r
		if n := len(runs); n > 0 {
			last := &runs[n-1]
			if last.delta == d {
				step := r - last.hi
				if last.lo == last.hi && (step == 1 || step == 2) {
					last.stride = step
					last.hi = r
					continue
				}
				if last.lo != last.hi && step == last.stride {
					last.hi = r
					continue
				}
			}
		}
		runs = append(runs, lowerRun{r, r, 1, d})
	}
	// Every rune must lowercase correctly under src/text/context.rs's
	// lookup: the last run starting at or below r.
	for r := rune(0); r <= unicode.MaxRune; r++ {
		i := sort.Search(len(runs), func(i int) bool { return runs[i].lo > r })
		got := r
		if i > 0 {
			run := runs[i-1]
			if r <= run.hi && (r-run.lo)%run.stride == 0 {
				got = r + run.delta
			}
		}
		if got != unicode.ToLower(r) {
			panic(fmt.Sprintf("lower runs disagree at %U", r))
		}
	}
	return runs
}

func rangeTable(b *strings.Builder, name, doc string, rs []runeRange) {
	fmt.Fprintf(b, "%s#[rustfmt::skip]\npub(super) const %s: &[(u32, u32)] = &[\n", doc, name)
	for i, r := range rs {
		if i%6 == 0 {
			b.WriteString("   ")
		}
		fmt.Fprintf(b, " (0x%x, 0x%x),", r.lo, r.hi)
		if i%6 == 5 || i == len(rs)-1 {
			b.WriteString("\n")
		}
	}
	b.WriteString("];\n")
}

func tables() string {
	var b strings.Builder
	b.WriteString("// Copyright 2026 Strims contributors\n// SPDX-License-Identifier: AGPL-3.0-only\n")
	b.WriteString("// Derived from chat-parser; see licenses/chat-parser.txt.\n")
	b.WriteString(generatedBy)
	b.WriteString("\n")
	rangeTable(&b, "SPACE",
		"/// Whitespace runes, as sorted disjoint inclusive ranges.\n",
		ranges(unicode.IsSpace))
	b.WriteString("\n")
	rangeTable(&b, "NON_WORD",
		"/// Runes that end a word (dashes, hyphens, math and pattern syntax,\n"+
			"/// quotation marks, terminal punctuation and whitespace), as sorted\n"+
			"/// disjoint inclusive ranges.\n",
		ranges(func(r rune) bool { return unicode.Is(nonWord, r) }))
	b.WriteString("\n")
	runs := lowerRuns()
	b.WriteString("/// The lowercase mapping as `(lo, hi, stride, delta)` runs sorted by `lo`:\n" +
		"/// a rune `r` in `lo..=hi` with `(r - lo) % stride == 0` lowercases to\n" +
		"/// `r + delta`, and every other rune to itself.\n")
	b.WriteString("#[rustfmt::skip]\npub(super) const TO_LOWER: &[(u32, u32, u32, i32)] = &[\n")
	for i, r := range runs {
		if i%4 == 0 {
			b.WriteString("   ")
		}
		fmt.Fprintf(&b, " (0x%x, 0x%x, %d, %d),", r.lo, r.hi, r.stride, r.delta)
		if i%4 == 3 || i == len(runs)-1 {
			b.WriteString("\n")
		}
	}
	b.WriteString("];\n")
	return b.String()
}

// ---- patterns ----

func escRune(b *strings.Builder, r rune) {
	if r < utf8.RuneSelf && (r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_') {
		b.WriteRune(r)
		return
	}
	fmt.Fprintf(b, `\x{%X}`, r)
}

func class(b *strings.Builder, rs []rune) {
	var pairs [][2]rune
	for i := 0; i+1 < len(rs); i += 2 {
		lo, hi := rs[i], rs[i+1]
		if lo >= 0xd800 && lo <= 0xdfff {
			lo = 0xe000
		}
		if hi >= 0xd800 && hi <= 0xdfff {
			hi = 0xd7ff
		}
		if lo > hi {
			continue
		}
		pairs = append(pairs, [2]rune{lo, hi})
	}
	if len(pairs) == 0 {
		b.WriteString(`[a&&b]`)
		return
	}
	var c strings.Builder
	c.WriteString("[")
	for _, p := range pairs {
		escRune(&c, p[0])
		if p[1] != p[0] {
			c.WriteString("-")
			escRune(&c, p[1])
		}
	}
	c.WriteString("]")
	if c.Len() < sharedClassLen {
		b.WriteString(c.String())
		return
	}
	i, ok := sharedClassIndex[c.String()]
	if !ok {
		i = len(sharedClasses)
		sharedClasses = append(sharedClasses, c.String())
		sharedClassIndex[c.String()] = i
	}
	fmt.Fprintf(b, "%c%d%c", classMark, i, classMark)
}

// Classes this long are printed once, as constants the patterns refer to.
const sharedClassLen = 1024

// classMark brackets a shared class's index in a printed pattern. NUL
// never appears in a printed pattern: escRune escapes it.
const classMark = '\x00'

var (
	sharedClasses    []string
	sharedClassIndex = map[string]int{}
)

func isASCIILetter(r rune) bool {
	return r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z'
}

// foldOrbit is every rune a FoldCase literal rune matches.
func foldOrbit(r rune) []rune {
	orbit := []rune{r}
	for f := unicode.SimpleFold(r); f != r; f = unicode.SimpleFold(f) {
		orbit = append(orbit, f)
	}
	sort.Slice(orbit, func(i, j int) bool { return orbit[i] < orbit[j] })
	return orbit
}

func literalRune(b *strings.Builder, r rune, fold bool) {
	if fold {
		if orbit := foldOrbit(r); len(orbit) > 1 {
			b.WriteString("[")
			for _, o := range orbit {
				escRune(b, o)
			}
			b.WriteString("]")
			return
		}
	}
	escRune(b, r)
}

// isAtom reports whether re prints as a single unit that a repetition can
// apply to without a group.
func isAtom(re *syntax.Regexp) bool {
	switch re.Op {
	case syntax.OpLiteral:
		return len(re.Rune) == 1
	case syntax.OpCharClass, syntax.OpAnyChar, syntax.OpAnyCharNotNL:
		return true
	}
	return false
}

func group(b *strings.Builder, re *syntax.Regexp) {
	b.WriteString("(?:")
	emit(b, re)
	b.WriteString(")")
}

func emit(b *strings.Builder, re *syntax.Regexp) {
	switch re.Op {
	case syntax.OpNoMatch:
		b.WriteString(`[a&&b]`)
	case syntax.OpEmptyMatch:
		b.WriteString(`(?:)`)
	case syntax.OpLiteral:
		fold := re.Flags&syntax.FoldCase != 0
		for i := 0; i < len(re.Rune); {
			// The Rust crate's tests check that (?i) folds each ASCII
			// letter to the same runes as unicode.SimpleFold.
			j := i
			for fold && j < len(re.Rune) && isASCIILetter(re.Rune[j]) {
				j++
			}
			if j > i {
				b.WriteString("(?i:" + string(re.Rune[i:j]) + ")")
				i = j
				continue
			}
			literalRune(b, re.Rune[i], fold)
			i++
		}
	case syntax.OpCharClass:
		class(b, re.Rune)
	case syntax.OpAnyCharNotNL:
		b.WriteString(`[^\n]`)
	case syntax.OpAnyChar:
		b.WriteString(`(?s:.)`)
	case syntax.OpBeginLine:
		b.WriteString(`(?m:^)`)
	case syntax.OpEndLine:
		b.WriteString(`(?m:$)`)
	case syntax.OpBeginText:
		b.WriteString(`\A`)
	case syntax.OpEndText:
		b.WriteString(`\z`)
	case syntax.OpWordBoundary:
		b.WriteString(`(?-u:\b)`)
	case syntax.OpNoWordBoundary:
		b.WriteString(`(?-u:\B)`)
	case syntax.OpCapture:
		group(b, re.Sub[0])
	case syntax.OpStar, syntax.OpPlus, syntax.OpQuest, syntax.OpRepeat:
		sub := re.Sub[0]
		if isAtom(sub) {
			emit(b, sub)
		} else {
			group(b, sub)
		}
		switch re.Op {
		case syntax.OpStar:
			b.WriteString("*")
		case syntax.OpPlus:
			b.WriteString("+")
		case syntax.OpQuest:
			b.WriteString("?")
		default:
			switch {
			case re.Max == -1:
				fmt.Fprintf(b, "{%d,}", re.Min)
			case re.Max == re.Min:
				fmt.Fprintf(b, "{%d}", re.Min)
			default:
				fmt.Fprintf(b, "{%d,%d}", re.Min, re.Max)
			}
		}
		if re.Flags&syntax.NonGreedy != 0 {
			b.WriteString("?")
		}
	case syntax.OpConcat:
		for _, sub := range re.Sub {
			if sub.Op == syntax.OpAlternate {
				group(b, sub)
			} else {
				emit(b, sub)
			}
		}
	case syntax.OpAlternate:
		for i, sub := range re.Sub {
			if i > 0 {
				b.WriteString("|")
			}
			emit(b, sub)
		}
	default:
		panic(fmt.Sprintf("unsupported regexp op %v", re.Op))
	}
}

// rustPattern prints a Go (RE2, Perl flags) pattern in the Rust regex
// dialect with the same meaning.
func rustPattern(expr string) string {
	re := must(syntax.Parse(expr, syntax.Perl))
	var b strings.Builder
	emit(&b, re)
	return b.String()
}

func rawLines(b *strings.Builder, s string) {
	const width = 96
	for len(s) > 0 {
		n := width
		if len(s) < n {
			n = len(s)
		}
		fmt.Fprintf(b, "    r\"%s\",\n", s[:n])
		s = s[n:]
	}
}

// patternConst writes a pattern as the fragments that concatenate to it.
func patternConst(b *strings.Builder, name, doc, pattern string) {
	fmt.Fprintf(b, "%s#[rustfmt::skip]\npub(crate) const %s: &[&str] = &[\n", doc, name)
	for i, part := range strings.Split(pattern, string(classMark)) {
		if i%2 == 1 {
			fmt.Fprintf(b, "    CLASS_%s,\n", part)
		} else {
			rawLines(b, part)
		}
	}
	b.WriteString("];\n")
}

func patterns() string {
	var b strings.Builder
	b.WriteString("// Copyright 2026 Strims contributors\n// SPDX-License-Identifier: AGPL-3.0-only\n")
	b.WriteString("// Derived from xurls and emojibase; see licenses/xurls.txt and licenses/emojibase.txt.\n")
	b.WriteString(generatedBy)
	b.WriteString("\n")
	patternConst(&b, "LINK",
		"/// URLs with or without a scheme, email addresses and IP addresses\n"+
			"/// (xurls v2.4.0 `Relaxed`). Matches are leftmost-longest.\n",
		rustPattern(xurls.Relaxed().String()))
	b.WriteString("\n")
	patternConst(&b, "SCHEME",
		"/// A scheme at the start of the haystack (xurls v2.4.0 `AnyScheme`).\n",
		rustPattern("^"+xurls.AnyScheme))
	b.WriteString("\n")
	patternConst(&b, "EMOJI",
		"/// Emoji sequences (emojibase `codepoint/emoji`). Matches are\n"+
			"/// leftmost-first.\n",
		rustPattern(chat.Emoji.String()))
	for i, c := range sharedClasses {
		fmt.Fprintf(&b, "\n/// A character class the patterns share.\n"+
			"#[rustfmt::skip]\nconst CLASS_%d: &str = concat!(\n", i)
		rawLines(&b, c)
		b.WriteString(");\n")
	}
	return b.String()
}

