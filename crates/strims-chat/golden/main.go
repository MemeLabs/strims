// Generates crates/strims-chat's rune tables, link and emoji patterns, and
// golden vectors from the Go implementation.
//
// Run from the repo root:
//
//	go run -tags golden ./crates/strims-chat/golden
//
// It writes:
//   - src/text/tables.rs: the lexer's space and non-word runes and the
//     lowercase mapping that nick matching folds with, from Go's unicode
//     tables and chat-parser's nonWord table;
//   - src/text/patterns.rs: xurls' Relaxed pattern, the "^" + AnyScheme
//     check and the emojibase pattern, parsed with regexp/syntax and printed
//     in the Rust regex dialect;
//   - golden/vectors.hex: lines of "<kind> <fields...>". The context lines
//     ("emote <name>", "modifier <name>", "internal_modifier <name>", "tag
//     <name>", "nick <nick> <peer key hex>") define one parser context.
//     "fold <letter> <rune hex>..." lists the runes a case-folded ASCII
//     letter matches, which patterns.rs writes as "(?i:...)".
//     Each "input <name> <input hex> <entities> <internal> <s-expression>"
//     line holds internal/chat's encoded Message_Entities without internal
//     modifiers, the same with every internal modifier at proc_chance 1
//     (only for inputs with exactly one emote), and chat-parser's AST. "="
//     is an empty value and "-" an absent one.
//
// Inputs are chat-parser's fuzz corpus (decoded to runes, so invalid UTF-8
// becomes U+FFFD), crafted ones, and ones drawn from fragments with a fixed
// seed, favouring those whose leftmost-longest link matches differ from
// leftmost-first ones. The extraction checks each emoji match
// against link and code block bounds with byte offsets; inputs where that
// decision differs from a rune-offset comparison are left out of the
// entities vectors and listed on stderr.
