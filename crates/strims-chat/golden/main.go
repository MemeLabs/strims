var w *bufio.Writer

func hexOrEmpty(b []byte) string {
	if len(b) == 0 {
		return "="
	}
	return hex.EncodeToString(b)
}

func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '\\' || r == '"':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\x{%X}`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func sexpr(b *strings.Builder, n parser.Node) {
	switch n := n.(type) {
	case *parser.Span:
		fmt.Fprintf(b, "(%s %d %d", n.Type, n.Pos(), n.End())
		for _, c := range n.Nodes {
			b.WriteByte(' ')
			sexpr(b, c)
		}
		b.WriteByte(')')
	case *parser.Emote:
		fmt.Fprintf(b, "(Emote %s %d %d", quote(n.Name), n.Pos(), n.End())
		for _, m := range n.Modifiers {
			b.WriteByte(' ')
			b.WriteString(quote(m))
		}
		b.WriteByte(')')
	case *parser.Tag:
		fmt.Fprintf(b, "(Tag %s %d %d)", quote(n.Name), n.Pos(), n.End())
	case *parser.Nick:
		fmt.Fprintf(b, "(Nick %s %d %d)", quote(n.Nick), n.Pos(), n.End())
	default:
		panic(fmt.Sprintf("unexpected node %T", n))
	}
}

func inBounds[T interface {
	GetBounds() *chatv1.Message_Entities_Bounds
}](ls []T, start, end int) bool {
	for _, l := range ls {
		b := l.GetBounds()
		if b.Start <= uint32(start) && b.End >= uint32(end) {
			return true
		}
	}
	return false
}

// mixesOffsets reports whether Extract's byte-offset check of an emoji
// match against link and code block bounds decides differently from a
// rune-offset check.
func mixesOffsets(msg string, e *chatv1.Message_Entities) bool {
	for _, b := range chat.Emoji.FindAllStringIndex(msg, -1) {
		rs := utf8.RuneCountInString(msg[:b[0]])
		re := rs + utf8.RuneCountInString(msg[b[0]:b[1]])
		byBytes := inBounds(e.Links, b[0], b[1]) || inBounds(e.CodeBlocks, b[0], b[1])
		byRunes := inBounds(e.Links, rs, re) || inBounds(e.CodeBlocks, rs, re)
		if byBytes != byRunes {
			return true
		}
	}
	return false
}

