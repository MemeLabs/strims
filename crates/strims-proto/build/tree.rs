//! Emits `tree.rs`: the module tree that mirrors the proto packages with the
//! common `strims.` prefix stripped, so `strims.network.v1.bootstrap` becomes
//! `crate::network::v1::bootstrap`.
//!
//! prost refers to types in other packages with relative `super::` paths
//! computed from the full package names. Every package shares the `strims`
//! root, so the paths stay valid with the crate root standing in for it.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use prost_types::FileDescriptorSet;

use crate::BoxError;
use crate::ident::sanitize_identifier;

const ROOT_PACKAGE: &str = "strims";

/// Lints silenced for generated code. The workspace's restriction lints
/// target hand-written code.
const GENERATED_ALLOWS: &str = "#[allow(\
clippy::all, clippy::pedantic, clippy::nursery, clippy::indexing_slicing, \
clippy::unwrap_used, clippy::expect_used, clippy::panic, missing_docs, \
rustdoc::all)]";

#[derive(Default)]
struct Node {
    package: Option<String>,
    children: BTreeMap<String, Node>,
}

pub fn generate(fds: &FileDescriptorSet, out_dir: &Path) -> Result<(), BoxError> {
    let mut root = Node::default();
    for file in &fds.file {
        let package = file.package();
        let rel = package
            .strip_prefix(ROOT_PACKAGE)
            .and_then(|p| p.strip_prefix('.'))
            .ok_or_else(|| {
                format!(
                    "{}: package {package:?} is outside {ROOT_PACKAGE}.*",
                    file.name()
                )
            })?;
        let mut node = &mut root;
        for segment in rel.split('.') {
            node = node.children.entry(segment.to_owned()).or_default();
        }
        node.package = Some(package.to_owned());
    }

    let mut out = String::from("// This file is @generated by strims-proto/build/tree.rs.\n\n");
    for (name, child) in &root.children {
        write_node(&mut out, name, child, 0, true)?;
    }
    fs::write(out_dir.join("tree.rs"), out)?;
    Ok(())
}

fn write_node(
    out: &mut String,
    name: &str,
    node: &Node,
    depth: usize,
    top: bool,
) -> Result<(), BoxError> {
    let indent = "    ".repeat(depth);
    match &node.package {
        Some(package) => writeln!(out, "{indent}/// Package `{package}`.")?,
        None => writeln!(out, "{indent}/// Packages under `{ROOT_PACKAGE}.{name}`.")?,
    }
    if top {
        writeln!(out, "{indent}{GENERATED_ALLOWS}")?;
    }
    writeln!(out, "{indent}pub mod {} {{", sanitize_identifier(name))?;
    if let Some(package) = &node.package {
        // prost names the file after the sanitized module path
        // (`strims.r#type.rs`), so ask prost-build for it.
        let file =
            prost_build::Module::from_protobuf_package_name(package).to_file_name_or(package);
        writeln!(
            out,
            "{indent}    include!(concat!(env!(\"OUT_DIR\"), \"/{file}\"));"
        )?;
    }
    for (child_name, child) in &node.children {
        write_node(out, child_name, child, depth + 1, false)?;
    }
    writeln!(out, "{indent}}}")?;
    Ok(())
}
