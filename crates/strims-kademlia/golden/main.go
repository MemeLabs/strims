//go:build golden

// Golden-vector generator for crates/strims-kademlia.
//
// Run from the repo root:
//
//	go run -tags golden ./crates/strims-kademlia/golden > crates/strims-kademlia/golden/vectors.txt
//
// Output lines are "<kind> key=value ..." with hex values; lists are comma
// separated and "-" means none.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/MemeLabs/strims/pkg/kademlia"
)

// evicted collects Evict calls. Evict runs on the replaced entry.
var evicted []kademlia.ID

type node struct{ id kademlia.ID }

func (n *node) ID() kademlia.ID { return n.id }
func (n *node) Evict()          { evicted = append(evicted, n.id) }

func hashID(s string) kademlia.ID {
	h := sha256.Sum256([]byte(s))
	id, err := kademlia.UnmarshalID(h[:])
	if err != nil {
		panic(err)
	}
	return id
}

func idHex(id kademlia.ID) string { return hex.EncodeToString(id.Bytes(nil)) }

func idList(is []kademlia.Interface) string {
	if len(is) == 0 {
		return "-"
	}
	s := make([]string, len(is))
	for i, n := range is {
		s[i] = idHex(n.ID())
	}
	return strings.Join(s, ",")
}

// near returns an id whose common prefix with self is about `shift` bits.
func near(self kademlia.ID, seed string, shift int) kademlia.ID {
	id := hashID(seed)
	id[0] >>= uint(shift)
	return id.XOr(self)
}

func main() {
	fmt.Println("# generated by: go run -tags golden ./crates/strims-kademlia/golden")

	ids := []kademlia.ID{kademlia.MinID, kademlia.MaxID, {1, 2, 3, 4}}
	for i := 0; i < 8; i++ {
		ids = append(ids, hashID(fmt.Sprintf("id-%d", i)))
	}
	for _, id := range ids {
		j, err := json.Marshal(id)
		if err != nil {
			panic(err)
		}
		fmt.Printf("id bytes=%s words=%016x,%016x,%016x,%016x string=%s json=%s\n",
			idHex(id), id[0], id[1], id[2], id[3], id.String(), j)
	}
	for i := 0; i+1 < len(ids); i++ {
		a, b := ids[i], ids[i+1]
		fmt.Printf("xor a=%s b=%s out=%s less=%t\n", idHex(a), idHex(b), idHex(a.XOr(b)), a.Less(b))
	}

	self := hashID("self")
	const k = 3
	b := kademlia.NewKBucket(self, k)
	fmt.Printf("kbucket self=%s k=%d\n", idHex(self), k)
	var inserted []kademlia.ID
	for i := 0; i < 400; i++ {
		var id kademlia.ID
		if i%17 == 16 && len(inserted) > 0 {
			id = inserted[(i*7)%len(inserted)] // duplicate attempt
		} else {
			id = near(self, fmt.Sprintf("node-%d", i), i%12)
		}
		evicted = evicted[:0]
		ok := b.Insert(&node{id: id})
		if ok {
			inserted = append(inserted, id)
		}
		ev := "-"
		if len(evicted) > 0 {
			ev = idHex(evicted[0])
		}
		fmt.Printf("insert id=%s ok=%t evicted=%s\n", idHex(id), ok, ev)
	}
	for i := 0; i < len(inserted); i += 5 {
		id := inserted[i]
		fmt.Printf("remove id=%s ok=%t\n", idHex(id), b.Remove(id))
	}
	all := b.Slice()
	fmt.Printf("slice ids=%s\n", idList(all))

	for i := 0; i < 40; i++ {
		var target kademlia.ID
		if i%2 == 0 {
			target = near(self, fmt.Sprintf("target-%d", i), i%14)
		} else {
			target = hashID(fmt.Sprintf("target-%d", i))
		}
		for _, n := range []int{1, 4, 10} {
			out := make([]kademlia.Interface, n)
			out = out[:b.Closest(target, out)]

			sorted := append([]kademlia.Interface(nil), all...)
			sort.Slice(sorted, func(i, j int) bool {
				return sorted[i].ID().XOr(target).Less(sorted[j].ID().XOr(target))
			})
			if len(sorted) > n {
				sorted = sorted[:n]
			}
			exact := idList(out) == idList(sorted)
			fmt.Printf("closest target=%s n=%d ids=%s exact=%t\n", idHex(target), n, idList(out), exact)
		}
	}
}
