"use strict";

/**
 * A webpack loader for a wasm crate's `Cargo.toml`, such as
 * `crates/strims-wasm/Cargo.toml` or `crates/strims-player/Cargo.toml`.
 *
 * It builds the crate its manifest's `[package]` names for wasm32 with cargo,
 * generates the `--target web` glue with wasm-bindgen-cli, and returns a
 * module that re-exports the glue. webpack then resolves the glue's
 * `new URL("<lib>_bg.wasm", import.meta.url)` as an asset, where `<lib>` is
 * the crate name with `_` for `-`.
 *
 * Options:
 * - `profile`: the cargo profile, "dev" or "release-wasm". "release-wasm"
 *   builds with `--locked`.
 * - `features`: crate features to enable (optional).
 *
 * The CLI must match the crate's `wasm-bindgen = "=X"` pin, because the glue
 * and the crate's bindings are generated by the same release.
 *
 * The glue lands in `<target dir>/<crate>-web/<profile>[+feature…]/`.
 * Only files whose bytes changed are replaced there, so an unchanged build
 * keeps the glue's mtimes and webpack's watcher sees nothing new.
 *
 * The module depends on everything under `crates/` and `schema/` and on the
 * workspace's cargo files, so watch mode rebuilds when Rust sources change.
 *
 * Builds in one process run one at a time. Cargo's lock on the target dir
 * orders builds across processes.
 */

const { spawn } = require("child_process");
const fs = require("fs");
const path = require("path");

const TARGET = "wasm32-unknown-unknown";
const PROFILES = ["dev", "release-wasm"];

/** The most stderr kept for an error message; cargo's output can be long. */
const STDERR_LIMIT = 1 << 20;

/** An error webpack reports by its message alone: the loader's stack says nothing. */
const buildError = (message) => Object.assign(new Error(message), { hideStack: true });

/** The tail of the build queue: each build starts once the one before it settles. */
let queue = Promise.resolve();

const serialize = (task) => {
  const result = queue.then(task);
  queue = result.catch(() => undefined);
  return result;
};

/**
 * Runs a command to completion. It resolves with the exit code and the
 * output, and rejects only when the command can't be started.
 */
const run = (command, args, { cwd, onStderr } = {}) =>
  new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd, env: process.env, stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "";
    let stderr = "";
    child.stdout.setEncoding("utf8");
    child.stderr.setEncoding("utf8");
    child.stdout.on("data", (chunk) => {
      stdout += chunk;
    });
    child.stderr.on("data", (chunk) => {
      stderr = (stderr + chunk).slice(-STDERR_LIMIT);
      if (onStderr) onStderr(chunk);
    });
    child.on("error", reject);
    child.on("close", (code, signal) => resolve({ code, signal, stdout, stderr }));
  });

const failed = (what, { code, signal, stderr }) =>
  buildError(`${what} failed (${signal ? `signal ${signal}` : `exit ${code}`}):\n${stderr}`);

/** The version in the manifest's `wasm-bindgen = "=X"` pin, or undefined. */
const bindgenPin = (manifest) => {
  const pin =
    /^\s*wasm-bindgen\s*=\s*(?:"=\s*([^"\s]+)"|\{[^}\n]*?\bversion\s*=\s*"=\s*([^"\s]+)")/m.exec(
      manifest
    );
  return pin ? pin[1] || pin[2] : undefined;
};

/** The crate name in the manifest's `[package]` table, or undefined. */
const packageName = (manifest) => {
  const table = /^\[package\]\s*$([\s\S]*?)(?=^\[|(?![\s\S]))/m.exec(manifest);
  const name = table && /^\s*name\s*=\s*"([^"]+)"/m.exec(table[1]);
  return name ? name[1] : undefined;
};

/** The crate's lib target: its name with `_` for `-`, as cargo names it. */
const libName = (crate) => crate.replace(/-/g, "_");

const checkBindgen = async (crate, pin) => {
  const hint = `${crate} needs wasm-bindgen-cli ${pin}: cargo install wasm-bindgen-cli --version ${pin} --locked`;
  let out;
  try {
    out = await run("wasm-bindgen", ["--version"]);
  } catch (e) {
    throw buildError(`${hint}\n(wasm-bindgen could not be run: ${e.message})`);
  }
  const found = /^wasm-bindgen\s+(\S+)/m.exec(out.stdout);
  if (out.code !== 0 || !found || found[1] !== pin) {
    const what = found ? `wasm-bindgen ${found[1]}` : `"${(out.stdout + out.stderr).trim()}"`;
    throw buildError(`${hint}\n(found ${what})`);
  }
};

const workspaces = new Map();

/** The workspace root and target dir for the crate in `crateDir`, from `cargo metadata`. */
const workspace = async (crateDir) => {
  const cached = workspaces.get(crateDir);
  if (cached) return cached;
  const out = await run("cargo", ["metadata", "--format-version", "1", "--no-deps"], {
    cwd: crateDir,
  });
  if (out.code !== 0) throw failed("cargo metadata", out);
  const { workspace_root: root, target_directory: targetDir } = JSON.parse(out.stdout);
  const ws = { root, targetDir };
  workspaces.set(crateDir, ws);
  return ws;
};

/** Makes the module depend on every input of the cargo build. */
const watch = (loader, root) => {
  loader.addContextDependency(path.join(root, "crates"));
  // strims-proto's build script compiles the .proto files under schema/.
  loader.addContextDependency(path.join(root, "schema"));
  for (const file of ["Cargo.toml", "Cargo.lock", ".cargo/config.toml", "rust-toolchain.toml"]) {
    const p = path.join(root, file);
    if (fs.existsSync(p)) {
      loader.addDependency(p);
    } else {
      loader.addMissingDependency(p);
    }
  }
};

/** Builds the crate's cdylib and resolves with the path of its .wasm file. */
const cargoBuild = async (root, crate, profile, features) => {
  const lib = libName(crate);
  const args = ["build", "-p", crate, "--lib", "--target", TARGET, "--profile", profile];
  if (profile === "release-wasm") args.push("--locked");
  if (features.length > 0) args.push("--features", features.join(","));
  args.push("--message-format=json-render-diagnostics");

  const out = await run("cargo", args, {
    cwd: root,
    onStderr: (chunk) => process.stderr.write(chunk),
  }).catch((e) => {
    throw buildError(`cargo could not be run: ${e.message}`);
  });
  if (out.code !== 0) throw failed(`cargo ${args.join(" ")}`, out);

  let wasm;
  for (const line of out.stdout.split("\n")) {
    if (!line.startsWith("{")) continue;
    const msg = JSON.parse(line);
    if (
      msg.reason === "compiler-artifact" &&
      msg.target &&
      msg.target.name === lib &&
      msg.target.kind.includes("cdylib")
    ) {
      wasm = msg.filenames.find((f) => f.endsWith(".wasm"));
    }
  }
  if (!wasm) throw buildError(`cargo ${args.join(" ")} reported no ${lib}.wasm`);
  return wasm;
};

const sameBytes = async (a, b) => {
  try {
    const [x, y] = await Promise.all([fs.promises.readFile(a), fs.promises.readFile(b)]);
    return x.equals(y);
  } catch (e) {
    if (e.code === "ENOENT") return false;
    throw e;
  }
};

/**
 * Makes `dest` hold exactly the files in `src`. A file whose bytes are
 * unchanged is left as it is; a changed one is replaced by renaming, so a
 * reader never sees it half-written. `src` and `dest` share a filesystem.
 */
const sync = async (src, dest) => {
  await fs.promises.mkdir(dest, { recursive: true });
  const entries = await fs.promises.readdir(src, { withFileTypes: true });
  const names = new Set(entries.map((e) => e.name));
  for (const e of entries) {
    const from = path.join(src, e.name);
    const to = path.join(dest, e.name);
    if (e.isDirectory()) {
      await sync(from, to);
    } else if (!(await sameBytes(from, to))) {
      await fs.promises.rename(from, to);
    }
  }
  for (const e of await fs.promises.readdir(dest, { withFileTypes: true })) {
    if (!names.has(e.name)) {
      await fs.promises.rm(path.join(dest, e.name), { recursive: true, force: true });
    }
  }
};

/** Generates the glue of `lib`'s `wasm` into `outDir` and resolves with the glue's path. */
const bindgen = async (wasm, lib, outDir) => {
  const parent = path.dirname(outDir);
  await fs.promises.mkdir(parent, { recursive: true });
  const tmp = await fs.promises.mkdtemp(path.join(parent, ".tmp-"));
  try {
    const args = ["--target", "web", "--no-typescript", "--out-name", lib];
    const out = await run("wasm-bindgen", [...args, "--out-dir", tmp, wasm]);
    if (out.code !== 0) throw failed(`wasm-bindgen ${args.join(" ")}`, out);
    await sync(tmp, outDir);
  } finally {
    await fs.promises.rm(tmp, { recursive: true, force: true });
  }
  return path.join(outDir, `${lib}.js`);
};

const parseOptions = (options) => {
  const { profile, features = [] } = options || {};
  if (!PROFILES.includes(profile)) {
    throw buildError(`strims-wasm-loader: profile must be one of ${PROFILES.join(", ")}`);
  }
  if (!Array.isArray(features) || !features.every((f) => typeof f === "string" && f !== "")) {
    throw buildError("strims-wasm-loader: features must be an array of feature names");
  }
  return { profile, features };
};

module.exports = function strimsWasmLoader(manifest) {
  const callback = this.async();
  let options;
  try {
    options = parseOptions(this.getOptions());
  } catch (e) {
    callback(e);
    return;
  }
  const { profile, features } = options;
  const outName = [profile, ...[...features].sort()].join("+");
  const crateDir = path.dirname(this.resourcePath);

  serialize(async () => {
    const crate = packageName(manifest);
    if (!crate) throw buildError(`${this.resourcePath} has no [package] name`);
    const { root, targetDir } = await workspace(crateDir);
    watch(this, root);
    const pin = bindgenPin(manifest);
    if (!pin) throw buildError(`${this.resourcePath} has no wasm-bindgen = "=X" pin`);
    await checkBindgen(crate, pin);
    const wasm = await cargoBuild(root, crate, profile, features);
    return bindgen(wasm, libName(crate), path.join(targetDir, `${crate}-web`, outName));
  }).then(
    (glue) => {
      const specifier = JSON.stringify(glue);
      callback(null, `export * from ${specifier};\nexport { default } from ${specifier};\n`);
    },
    (e) => callback(e)
  );
};
